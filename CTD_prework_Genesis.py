# Small greeting with a stranger
# This script greets the user, asks for their name and age, and
# compares it to my age (25)

print("Hi, I'm Genesis!")

# Ask for their name
name = input("What is your name?: ")
print("Nice to meet you " + name + "!")

# Am I older or younger?
age = input("How old are you? (Type in a number) : ")
print(name + " you are " + age +" years old.")

age_diff = (25 - float(age))
if age_diff > 0:
    print("I am " + str(age_diff) + " years older than you.")
elif age_diff < 0:
    print("I am " + str(abs(age_diff)) + " years younger than you.")
else:
    print("We are the same age!")

